namespace CarinaStudio.AppSuite;

/// <summary>
/// Predefined text shell.
/// </summary>
public enum TextShell
{
    /// <summary>
    /// bash.
    /// </summary>
    BourneAgainShell,
    /// <summary>
    /// sh.
    /// </summary>
    BourneShell,
    /// <summary>
    /// Windows CMD.
    /// </summary>
    CommandPrompt,
    /// <summary>
    /// csh.
    /// </summary>
    CShell,
    /// <summary>
    /// fish.
    /// </summary>
    FriendlyInteractiveShell,
    /// <summary>
    /// PowerShell 7 ('pwsh'), or Windows PowerShell if PowerShell 7 is not installed.
    /// </summary>
    PowerShell,
    /// <summary>
    /// zsh.
    /// </summary>
    ZShell,
}